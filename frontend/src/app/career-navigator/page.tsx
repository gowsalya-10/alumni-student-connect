'use client';

import React, { useEffect, useState } from 'react';
import { DashboardLayout } from '@/components/layout/DashboardLayout';
import { Card } from '@/components/ui/Card';
import { Button } from '@/components/ui/Button';
import { Skeleton } from '@/components/feedback/Skeleton';
import { Alert } from '@/components/feedback/Alert';
import { EmptyState } from '@/components/feedback/EmptyState';
import { 
  Compass, Zap, Target, BrainCircuit, RefreshCw, Clock, 
  CheckCircle2, Circle 
} from 'lucide-react';
import api from '@/lib/api';
import { CareerRoadmap, RoadmapPhase, RoadmapMilestone } from '@/types';

export default function CareerNavigatorPage() {
  const [roadmap, setRoadmap] = useState<CareerRoadmap | null>(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    let ignore = false;
    const loadRoadmap = async () => {
      try {
        const res = await api.get('/api/v1/roadmap');
        if (!ignore) setRoadmap(res.data);
      } catch {
        if (!ignore) setError('Failed to load your career roadmap.');
      } finally {
        if (!ignore) setLoading(false);
      }
    };
    loadRoadmap();
    return () => { ignore = true; };
  }, []);

  const handleGenerate = async () => {
    try {
      setGenerating(true);
      setError('');
      const res = await api.post('/api/v1/roadmap/generate', {});
      setRoadmap(res.data);
    } catch {
      setError('Failed to generate career roadmap. Please try again later.');
    } finally {
      setGenerating(false);
    }
  };

  if (loading) {
    return (
      <DashboardLayout>
        <div className="p-4 sm:p-8 max-w-5xl mx-auto space-y-6">
          <Skeleton className="h-10 w-48 rounded-xl" />
          <Skeleton className="h-32 w-full rounded-2xl" />
          <div className="space-y-4">
            <Skeleton className="h-28 w-full rounded-2xl" />
            <Skeleton className="h-28 w-full rounded-2xl" />
          </div>
        </div>
      </DashboardLayout>
    );
  }

  // Calculate milestone stats
  let totalMilestones = 0;
  let completedMilestones = 0;
  if (roadmap) {
    roadmap.phases.forEach(p => {
      totalMilestones += p.milestones.length;
      completedMilestones += p.milestones.filter(m => m.is_completed).length;
    });
  }
  const progressPercent = totalMilestones > 0 ? Math.round((completedMilestones / totalMilestones) * 100) : 0;

  return (
    <DashboardLayout>
      <div className="p-4 sm:p-8 max-w-5xl mx-auto space-y-8 animate-fade-in font-sans">
        
        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 dark:text-white flex items-center gap-2.5">
              <div className="h-9 w-9 rounded-xl bg-gradient-to-tr from-indigo-600 to-violet-600 text-white flex items-center justify-center shadow-xs">
                <BrainCircuit className="h-5 w-5" />
              </div>
              AI Career Navigator
            </h1>
            <p className="text-xs sm:text-sm text-slate-500 dark:text-slate-400 mt-1 max-w-2xl">
              Personalized, phased milestones generated by AI to guide your pathway from college to industry.
            </p>
          </div>
          
          {roadmap && (
            <Button 
              variant="outline" 
              size="sm"
              onClick={handleGenerate} 
              disabled={generating}
              className="gap-2 shrink-0 border-indigo-200 text-indigo-700 dark:text-indigo-300 font-semibold"
            >
              <RefreshCw className={`h-3.5 w-3.5 ${generating ? 'animate-spin' : ''}`} />
              {generating ? 'Regenerating...' : 'Regenerate Roadmap'}
            </Button>
          )}
        </div>

        {error && <Alert variant="error" title="Notice">{error}</Alert>}

        {!roadmap && !loading && !error && (
          <Card className="p-12 text-center border-dashed border-slate-200 dark:border-slate-800 rounded-2xl bg-white dark:bg-slate-900">
            <EmptyState
              icon={<Compass className="h-12 w-12 text-indigo-500" />}
              title="No Career Roadmap Generated Yet"
              description="Ready to plan your engineering career? Generate an AI-powered step-by-step roadmap tailored to your desired career and industry."
              action={
                <Button 
                  size="md" 
                  onClick={handleGenerate} 
                  disabled={generating}
                  className="gap-2 bg-indigo-600 hover:bg-indigo-700 text-white"
                >
                  <Zap className="h-4 w-4" />
                  {generating ? 'Generating with AI...' : 'Generate My Career Roadmap'}
                </Button>
              }
              className="border-none bg-transparent"
            />
          </Card>
        )}

        {roadmap && (
          <div className="space-y-8">
            
            {/* Top Roadmap Overview Card */}
            <div className="p-6 rounded-3xl bg-gradient-to-r from-indigo-900 via-indigo-850 to-violet-900 text-white shadow-sm space-y-5">
              <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
                <div>
                  <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold bg-white/10 text-indigo-200 backdrop-blur-xs mb-2">
                    <Target className="h-3.5 w-3.5" /> Target Role
                  </span>
                  <h2 className="text-2xl font-extrabold tracking-tight">
                    {roadmap.career_goal || 'Software Engineer'}
                  </h2>
                  <p className="text-xs sm:text-sm text-indigo-200 mt-1">
                    Domain: <span className="font-semibold text-white">{roadmap.recommended_domain || 'Technology'}</span> • Estimated Focus: <span className="font-semibold text-white">{roadmap.estimated_focus || 'Self-paced'}</span>
                  </p>
                </div>

                <div className="p-4 rounded-2xl bg-white/10 backdrop-blur-xs text-right min-w-[140px]">
                  <p className="text-xs text-indigo-200 font-medium">Roadmap Progress</p>
                  <p className="text-2xl font-extrabold text-white mt-0.5">{progressPercent}%</p>
                  <p className="text-[11px] text-indigo-300 mt-0.5">{completedMilestones} of {totalMilestones} Completed</p>
                </div>
              </div>

              {roadmap.explanation && (
                <p className="text-xs sm:text-sm text-indigo-100/90 border-t border-white/10 pt-4 leading-relaxed">
                  {roadmap.explanation}
                </p>
              )}
            </div>

            {/* Phased Milestones Breakdown */}
            <div className="space-y-8">
              {roadmap.phases.map((phase: RoadmapPhase, pIndex: number) => (
                <div key={phase.id} className="space-y-4">
                  <div className="flex items-center gap-3">
                    <span className="h-8 w-8 rounded-xl bg-indigo-600 text-white text-xs font-bold flex items-center justify-center shadow-2xs">
                      0{pIndex + 1}
                    </span>
                    <h3 className="text-lg font-bold text-slate-900 dark:text-white">
                      Phase {pIndex + 1}: {phase.phase_name}
                    </h3>
                  </div>

                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                    {phase.milestones.map((m: RoadmapMilestone) => (
                      <Card 
                        key={m.id} 
                        className={`p-5 rounded-2xl border transition-all ${
                          m.is_completed 
                            ? 'bg-emerald-50/40 dark:bg-emerald-950/20 border-emerald-200 dark:border-emerald-800' 
                            : 'bg-white dark:bg-slate-900 border-slate-200/80 dark:border-slate-800 shadow-2xs'
                        }`}
                      >
                        <div className="flex items-start justify-between gap-3 mb-2">
                          <h4 className="font-bold text-sm text-slate-900 dark:text-white flex items-center gap-2">
                            {m.is_completed ? (
                              <CheckCircle2 className="h-4 w-4 text-emerald-600 shrink-0" />
                            ) : (
                              <Circle className="h-4 w-4 text-slate-400 shrink-0" />
                            )}
                            {m.skill_name}
                          </h4>

                          <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full uppercase tracking-wider shrink-0 ${
                            m.difficulty.toLowerCase() === 'beginner'
                              ? 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300'
                              : m.difficulty.toLowerCase() === 'intermediate'
                              ? 'bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-300'
                              : 'bg-purple-100 text-purple-800 dark:bg-purple-950 dark:text-purple-300'
                          }`}>
                            {m.difficulty}
                          </span>
                        </div>

                        <p className="text-xs text-slate-600 dark:text-slate-300 line-clamp-3 leading-relaxed mb-3">
                          {m.description}
                        </p>

                        <div className="flex items-center justify-between text-[11px] text-slate-500 dark:text-slate-400 pt-2 border-t border-slate-100 dark:border-slate-800">
                          <span className="flex items-center gap-1">
                            <Clock className="h-3 w-3" />
                            {m.estimated_time}
                          </span>
                          <span className={`font-semibold ${m.is_completed ? 'text-emerald-600' : 'text-slate-400'}`}>
                            {m.is_completed ? 'Completed' : 'Pending Milestone'}
                          </span>
                        </div>
                      </Card>
                    ))}
                  </div>
                </div>
              ))}
            </div>

          </div>
        )}

      </div>
    </DashboardLayout>
  );
}
